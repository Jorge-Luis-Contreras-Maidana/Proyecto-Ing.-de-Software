-- Vincula las justificaciones aceptadas con las asistencias de la misma fecha.
UPDATE asistencias a
SET estado = 'justificada', hora_ingreso = NULL, hora_salida_aula = NULL,
    metodo_ingreso = 'no_aplica', id_justificacion = j.id_justificacion,
    observacion = 'Ausencia justificada por solicitud aprobada del tutor.'
FROM sesiones_clase sc
JOIN justificaciones_ausencia j
  ON j.fecha_inicio = sc.fecha
 AND j.fecha_fin = sc.fecha
 AND j.estado = 'justificada'
WHERE a.id_sesion_clase = sc.id_sesion_clase
  AND a.id_estudiante = j.id_estudiante
  AND a.estado = 'ausente';

