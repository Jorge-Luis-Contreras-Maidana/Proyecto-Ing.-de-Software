-- =====================================================================
-- SESCO - Base de datos de demostración para PostgreSQL
-- Institución ficticia: Unidad Educativa Nueva Esperanza (La Paz, Bolivia)
-- Ejecutar una sola vez en una base de datos de pruebas vacía.
-- Esquema: sesco
-- IMPORTANTE: contraseñas y secretos QR son marcadores de demostración.
-- En producción, generar hashes seguros y secretos TOTP desde la aplicación.
-- Todas las columnas temporales usan TIMESTAMP local; las conexiones deben fijar America/La_Paz.
-- El índice de lecturas QR refuerza la unicidad, pero la validación TOTP y la
-- transacción de asistencia deben implementarse en el backend.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS sesco;
SET search_path TO sesco, public;
SET TIME ZONE 'America/La_Paz';

-- 1. Catálogos e institución
CREATE TABLE roles (
    id_rol SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);

CREATE TABLE unidades_educativas (
    id_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    direccion VARCHAR(180) NOT NULL,
    ciudad VARCHAR(60) NOT NULL DEFAULT 'La Paz',
    departamento VARCHAR(60) NOT NULL DEFAULT 'La Paz',
    telefono VARCHAR(30),
    estado VARCHAR(15) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa','inactiva'))
);

CREATE TABLE gestiones_escolares (
    id_gestion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad INTEGER NOT NULL REFERENCES unidades_educativas(id_unidad),
    anio SMALLINT NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('planificada','activa','cerrada')),
    UNIQUE (id_unidad, anio),
    CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    nombre_usuario VARCHAR(60) NOT NULL UNIQUE,
    correo VARCHAR(150) UNIQUE,
    telefono VARCHAR(30),
    hash_contrasena TEXT NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo','bloqueado')),
    debe_cambiar_contrasena BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE usuarios_roles (
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario) ON DELETE CASCADE,
    id_rol SMALLINT NOT NULL REFERENCES roles(id_rol),
    PRIMARY KEY (id_usuario, id_rol)
);

CREATE TABLE sesiones_usuario (
    id_sesion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    iniciada_en TIMESTAMP NOT NULL,
    ultima_actividad TIMESTAMP NOT NULL,
    expira_en TIMESTAMP NOT NULL,
    cerrada_en TIMESTAMP,
    direccion_ip INET,
    CHECK (expira_en >= iniciada_en)
);

-- 2. Personas y organización académica
CREATE TABLE cursos (
    id_curso INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad INTEGER NOT NULL REFERENCES unidades_educativas(id_unidad),
    nivel VARCHAR(40) NOT NULL,
    grado SMALLINT NOT NULL CHECK (grado BETWEEN 1 AND 6),
    paralelo CHAR(1) NOT NULL,
    turno VARCHAR(15) NOT NULL CHECK (turno IN ('manana','tarde','noche')),
    UNIQUE (id_unidad, nivel, grado, paralelo, turno)
);

CREATE TABLE estudiantes (
    id_estudiante INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER UNIQUE REFERENCES usuarios(id_usuario),
    codigo_estudiante VARCHAR(25) NOT NULL UNIQUE,
    nombres VARCHAR(80) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    genero VARCHAR(20),
    estado VARCHAR(15) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','retirado','egresado'))
);

CREATE TABLE observaciones_estudiante (
    id_observacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    registrada_por INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(25) NOT NULL CHECK (tipo IN ('academica','asistencia','comportamiento','convivencia','otra')),
    descripcion TEXT NOT NULL,
    confidencial BOOLEAN NOT NULL DEFAULT FALSE,
    estado VARCHAR(15) NOT NULL DEFAULT 'activa' CHECK (estado IN ('activa','archivada'))
);

CREATE TABLE tutores (
    id_tutor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL UNIQUE REFERENCES usuarios(id_usuario),
    documento_identidad VARCHAR(30) UNIQUE,
    ocupacion VARCHAR(80),
    confirmado_por INTEGER REFERENCES usuarios(id_usuario),
    confirmado_en TIMESTAMP,
    estado VARCHAR(15) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','confirmado','rechazado','inactivo')),
    CHECK ((estado <> 'confirmado') OR (confirmado_por IS NOT NULL AND confirmado_en IS NOT NULL))
);

CREATE TABLE profesores (
    id_profesor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL UNIQUE REFERENCES usuarios(id_usuario),
    codigo_docente VARCHAR(25) NOT NULL UNIQUE,
    especialidad VARCHAR(100),
    fecha_contratacion DATE,
    estado VARCHAR(15) NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo','inactivo'))
);

CREATE TABLE estudiante_tutor (
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    id_tutor INTEGER NOT NULL REFERENCES tutores(id_tutor),
    parentesco VARCHAR(30) NOT NULL,
    es_contacto_principal BOOLEAN NOT NULL DEFAULT FALSE,
    confirmado BOOLEAN NOT NULL DEFAULT FALSE,
    confirmado_por INTEGER REFERENCES usuarios(id_usuario),
    confirmado_en TIMESTAMP,
    PRIMARY KEY (id_estudiante, id_tutor),
    CHECK (NOT confirmado OR (confirmado_por IS NOT NULL AND confirmado_en IS NOT NULL))
);

CREATE UNIQUE INDEX uq_tutor_principal_por_estudiante
ON estudiante_tutor(id_estudiante) WHERE es_contacto_principal;

CREATE TABLE inscripciones (
    id_inscripcion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    id_curso INTEGER NOT NULL REFERENCES cursos(id_curso),
    id_gestion INTEGER NOT NULL REFERENCES gestiones_escolares(id_gestion),
    fecha_inscripcion DATE NOT NULL,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('inscrito','trasladado','retirado','finalizado')),
    UNIQUE (id_estudiante, id_gestion)
);

CREATE TABLE materias (
    id_materia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);

CREATE TABLE asignaciones_docentes (
    id_asignacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesor INTEGER NOT NULL REFERENCES profesores(id_profesor),
    id_curso INTEGER NOT NULL REFERENCES cursos(id_curso),
    id_materia INTEGER NOT NULL REFERENCES materias(id_materia),
    id_gestion INTEGER NOT NULL REFERENCES gestiones_escolares(id_gestion),
    UNIQUE (id_profesor, id_curso, id_materia, id_gestion)
);

-- 3. QR, sesiones, asistencia y salidas
CREATE TABLE credenciales_qr (
    id_credencial INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    secreto_totp_cifrado TEXT NOT NULL,
    emitida_en TIMESTAMP NOT NULL,
    revocada_en TIMESTAMP,
    estado VARCHAR(15) NOT NULL CHECK (estado IN ('activa','revocada','suspendida')),
    UNIQUE (id_estudiante, emitida_en),
    CHECK (revocada_en IS NULL OR revocada_en >= emitida_en)
);

-- Una sola credencial activa por estudiante; permite conservar credenciales revocadas.
CREATE UNIQUE INDEX uq_credencial_activa
ON credenciales_qr(id_estudiante)
WHERE estado = 'activa';

CREATE TABLE sesiones_clase (
    id_sesion_clase INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_asignacion INTEGER NOT NULL REFERENCES asignaciones_docentes(id_asignacion),
    fecha DATE NOT NULL,
    hora_inicio_prevista TIME NOT NULL,
    hora_apertura_real TIMESTAMP,
    hora_cierre_real TIMESTAMP,
    abierta_por INTEGER REFERENCES usuarios(id_usuario),
    hora_fin_prevista TIME NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'programada' CHECK (estado IN ('programada','abierta','cerrada','cancelada','pendiente_reprogramacion')),
    observacion TEXT,
    CHECK (hora_fin_prevista > hora_inicio_prevista),
    UNIQUE (id_asignacion, fecha, hora_inicio_prevista)
);

CREATE TABLE configuracion_asistencia (
    id_configuracion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad INTEGER NOT NULL REFERENCES unidades_educativas(id_unidad),
    tolerancia_ingreso_min SMALLINT NOT NULL DEFAULT 5 CHECK (tolerancia_ingreso_min BETWEEN 0 AND 60),
    limite_tardanza_min SMALLINT NOT NULL DEFAULT 15 CHECK (limite_tardanza_min BETWEEN 1 AND 180),
    ausencias_consecutivas_alerta SMALLINT NOT NULL DEFAULT 3 CHECK (ausencias_consecutivas_alerta >= 1),
    tardanzas_mes_alerta SMALLINT NOT NULL DEFAULT 5 CHECK (tardanzas_mes_alerta >= 1),
    porcentaje_ausencia_alerta NUMERIC(5,2) NOT NULL DEFAULT 20 CHECK (porcentaje_ausencia_alerta BETWEEN 0 AND 100),
    plazo_justificacion_dias SMALLINT NOT NULL DEFAULT 3 CHECK (plazo_justificacion_dias BETWEEN 0 AND 90),
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por INTEGER REFERENCES usuarios(id_usuario),
    UNIQUE (id_unidad)
);

CREATE TABLE asistencias (
    id_asistencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sesion_clase INTEGER NOT NULL REFERENCES sesiones_clase(id_sesion_clase),
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('presente','tarde','ausente','justificada','pendiente')),
    hora_ingreso TIMESTAMP,
    hora_salida_aula TIMESTAMP,
    metodo_ingreso VARCHAR(15) CHECK (metodo_ingreso IN ('qr','manual','no_aplica')),
    registrado_por INTEGER REFERENCES usuarios(id_usuario),
    observacion TEXT,
    UNIQUE (id_sesion_clase, id_estudiante),
    CHECK (hora_salida_aula IS NULL OR hora_ingreso IS NULL OR hora_salida_aula >= hora_ingreso)
);

-- Registro de lecturas QR. El backend debe validar TOTP, vigencia y permisos antes de aceptar.
CREATE TABLE lecturas_qr (
    id_lectura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_credencial INTEGER NOT NULL REFERENCES credenciales_qr(id_credencial),
    id_asistencia BIGINT UNIQUE REFERENCES asistencias(id_asistencia),
    ventana_totp BIGINT NOT NULL,
    leido_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resultado VARCHAR(20) NOT NULL CHECK (resultado IN ('aceptado','rechazado','duplicado','expirado')),
    motivo_rechazo TEXT,
    huella_codigo VARCHAR(128),
    CHECK (resultado = 'aceptado' OR id_asistencia IS NULL)
);

-- Evita aceptar más de una vez el mismo QR de una credencial dentro de una ventana TOTP.
-- Las lecturas rechazadas también se pueden conservar para auditoría.
CREATE UNIQUE INDEX uq_lectura_qr_credencial_ventana_aceptada
ON lecturas_qr(id_credencial, ventana_totp)
WHERE resultado = 'aceptado';

CREATE TABLE avisos_inasistencia_docente (
    id_aviso_docente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesor INTEGER NOT NULL REFERENCES profesores(id_profesor),
    id_sesion_clase INTEGER REFERENCES sesiones_clase(id_sesion_clase),
    fecha_afectada DATE NOT NULL,
    motivo TEXT NOT NULL,
    enviado_en TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','revisado','rechazado','resuelto')),
    revisado_por INTEGER REFERENCES usuarios(id_usuario),
    revisado_en TIMESTAMP,
    decision TEXT,
    CHECK ((revisado_por IS NULL AND revisado_en IS NULL) OR (revisado_por IS NOT NULL AND revisado_en IS NOT NULL))
);

CREATE TABLE autorizaciones_salida (
    id_autorizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso INTEGER NOT NULL REFERENCES cursos(id_curso),
    id_gestion INTEGER NOT NULL REFERENCES gestiones_escolares(id_gestion),
    id_aviso_docente INTEGER REFERENCES avisos_inasistencia_docente(id_aviso_docente),
    solicitada_por INTEGER NOT NULL REFERENCES usuarios(id_usuario),
    autorizada_por INTEGER REFERENCES usuarios(id_usuario),
    fecha_salida DATE NOT NULL,
    hora_salida_prevista TIME NOT NULL,
    motivo TEXT NOT NULL,
    solicitada_en TIMESTAMP NOT NULL,
    resuelta_en TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','autorizada','rechazada','cancelada','finalizada')),
    observacion TEXT,
    CHECK ((estado IN ('pendiente','cancelada') AND resuelta_en IS NULL) OR (estado IN ('autorizada','rechazada','finalizada') AND autorizada_por IS NOT NULL AND resuelta_en IS NOT NULL))
);

CREATE TABLE registros_salida (
    id_registro_salida BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    id_gestion INTEGER NOT NULL REFERENCES gestiones_escolares(id_gestion),
    id_curso INTEGER NOT NULL REFERENCES cursos(id_curso),
    id_autorizacion INTEGER REFERENCES autorizaciones_salida(id_autorizacion),
    fecha_salida DATE NOT NULL,
    hora_salida_real TIMESTAMP,
    metodo_registro VARCHAR(15) NOT NULL CHECK (metodo_registro IN ('qr','manual','lista')),
    estado_verificacion VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado_verificacion IN ('pendiente','confirmada','observada')),
    registrado_por INTEGER REFERENCES usuarios(id_usuario),
    observacion TEXT,
    CHECK (estado_verificacion <> 'confirmada' OR (hora_salida_real IS NOT NULL AND registrado_por IS NOT NULL))
);

-- 4. Ausencias justificadas, seguimiento y comunicación
CREATE TABLE justificaciones_ausencia (
    id_justificacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante INTEGER NOT NULL REFERENCES estudiantes(id_estudiante),
    id_tutor INTEGER NOT NULL REFERENCES tutores(id_tutor),
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    motivo_declarado TEXT NOT NULL,
    documento_referencia TEXT,
    solicitada_en TIMESTAMP NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','avisada','justificada','no_justificada','requiere_informacion')),
    revisada_por INTEGER REFERENCES usuarios(id_usuario),
    revisada_en TIMESTAMP,
    comentario_revision TEXT,
    CHECK (fecha_fin >= fecha_inicio),
    CHECK ((revisada_por IS NULL AND revisada_en IS NULL) OR (revisada_por IS NOT NULL AND revisada_en IS NOT NULL))
);

-- Una asistencia puede quedar enlazada con la justificación que la respalda.
