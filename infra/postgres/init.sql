INSERT INTO asistencias (id_asistencia,id_sesion_clase,id_estudiante,estado,hora_ingreso,hora_salida_aula,metodo_ingreso,registrado_por,observacion)
SELECT row_number() OVER (ORDER BY sc.id_sesion_clase, i.id_estudiante)::bigint,
       sc.id_sesion_clase, i.id_estudiante,
       CASE WHEN (i.id_estudiante + sc.id_sesion_clase) % 17 = 0 THEN 'ausente'
            WHEN (i.id_estudiante + sc.id_sesion_clase) % 9 = 0 THEN 'tarde'
            ELSE 'presente' END,
       CASE WHEN (i.id_estudiante + sc.id_sesion_clase) % 17 = 0 THEN NULL
            ELSE (sc.fecha + sc.hora_inicio_prevista) +
                 CASE WHEN (i.id_estudiante + sc.id_sesion_clase) % 9 = 0 THEN interval '9 minutes' ELSE interval '2 minutes' END END,
       CASE WHEN (i.id_estudiante + sc.id_sesion_clase) % 17 = 0 THEN NULL
            ELSE (sc.fecha + sc.hora_fin_prevista) END,
       CASE WHEN (i.id_estudiante + sc.id_sesion_clase) % 17 = 0 THEN 'no_aplica'
            WHEN (i.id_estudiante + sc.id_sesion_clase) % 13 = 0 THEN 'manual' ELSE 'qr' END,
       (SELECT p.id_usuario FROM asignaciones_docentes ad JOIN profesores p ON p.id_profesor=ad.id_profesor WHERE ad.id_asignacion=sc.id_asignacion),
       CASE WHEN (i.id_estudiante + sc.id_sesion_clase) % 17 = 0 THEN 'Ausencia registrada'
            WHEN (i.id_estudiante + sc.id_sesion_clase) % 9 = 0 THEN 'Ingreso posterior a la tolerancia'
            ELSE NULL END
FROM sesiones_clase sc
JOIN asignaciones_docentes ad ON ad.id_asignacion=sc.id_asignacion
JOIN inscripciones i ON i.id_curso=ad.id_curso AND i.id_gestion=3 AND i.estado='inscrito'
WHERE sc.fecha >= DATE '2026-01-01'
ON CONFLICT (id_sesion_clase,id_estudiante) DO NOTHING;

