-- Vista diaria para alertas y reportes consolidados por estudiante y fecha.
CREATE OR REPLACE VIEW v_asistencia_diaria AS
SELECT a.id_estudiante,
       sc.fecha,
       COUNT(*) AS total_clases,
       COUNT(*) FILTER (WHERE a.estado='presente') AS presentes,
       COUNT(*) FILTER (WHERE a.estado='tarde') AS tardanzas,
       COUNT(*) FILTER (WHERE a.estado='ausente') AS ausencias,
       COUNT(*) FILTER (WHERE a.estado='justificada') AS justificadas,
       COUNT(*) FILTER (WHERE a.estado='pendiente') AS pendientes,
       MIN(a.hora_ingreso) FILTER (WHERE a.hora_ingreso IS NOT NULL) AS primer_ingreso,
       MAX(a.hora_salida_aula) FILTER (WHERE a.hora_salida_aula IS NOT NULL) AS ultima_salida
FROM asistencias a
JOIN sesiones_clase sc ON sc.id_sesion_clase=a.id_sesion_clase
GROUP BY a.id_estudiante, sc.fecha;

